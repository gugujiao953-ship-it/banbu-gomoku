import { chromium } from "playwright";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const ROOT = path.resolve(fileURLToPath(new URL("../", import.meta.url)));
const HTML = path.join(ROOT, "video", "promo-v2.html");
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1, locale: "zh-CN" });
const page = await context.newPage();
const failures = []; const errors = [];
page.on("requestfailed", r => failures.push(r.url()));
page.on("pageerror", e => errors.push(e.message));
await page.goto(pathToFileURL(HTML).href, { waitUntil: "load", timeout: 90000 });
await page.waitForFunction(() => [...document.images].every(i => i.complete), null, { timeout: 90000 });
await page.waitForFunction(() => !!window.__promo, null, { timeout: 30000 });
const checkTimes = [0, 4, 11, 17, 24, 31, 42, 51, 58, 65, 73, 77.9];
const result = await page.evaluate(times => times.map(t => { window.__promo.renderFrame(t); return { t, active: [...document.querySelectorAll(".seg.on")].map(e => e.id), broken: [...document.images].filter(i => i.naturalWidth === 0).length }; }), checkTimes);
console.log(JSON.stringify({ meta: await page.evaluate(() => ({ duration: window.__promo.DURATION, fps: window.__promo.FPS })), result, failures: failures.length, errors }, null, 2));
if (failures.length || errors.length || result.some(r => r.active.length !== 1 || r.broken)) process.exitCode = 1;
await context.close(); await browser.close();
