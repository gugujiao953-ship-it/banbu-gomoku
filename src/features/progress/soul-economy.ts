/**
 * 棋魂的**经济数据**：来源定价、消费登记、默认调度。
 *
 * ⚠ **本文件由「成就工坊」管理**（`scripts/apply-achievement-workshop.mjs` 会把工坊导出的
 * JSON 直接写成这个文件）。手改当然也能生效，但下次从工坊应用会**覆盖**掉，
 * 所以「调价」「加来源」「加消费点」这些事请优先在工坊里做。
 *
 * ## 为什么把数据从 `soul.ts` 搬出来
 *
 * `soul.ts` 是**账务逻辑**（账本读写、幂等、折叠、余额），它不该跟着定价一起改。
 * 分成两个文件之后有一条清晰的分界：
 *
 *   · 逻辑（soul.ts）—— 改动要过单测、要审；
 *   · 数据（本文件）—— 改一个数字就能生效，工坊可以整文件重写。
 *
 * 这也是 `achievement-catalog.ts` 之于 `achievements.ts` 的同一条分界。
 * 运行期依赖是单向的：`soul.ts` → 本文件；本文件只从 `soul.ts` 引**类型**（编译期擦除），
 * 所以不存在循环依赖。
 *
 * ## 三条口径（改数字时别破坏）
 *
 *  1. **来源必须能解释**：每一条都要对应一个真实发生的事件（下完一局、解出一题），
 *     否则账本会变成"来路不明的进账"，用户看不出钱是怎么来的；
 *  2. **越难越值钱，但不夸张**：日常在做的事慢慢攒出消费能力，不是打一局就暴富；
 *  3. **不发明消费点**：`SOUL_SPEND_POINTS` 里每一条都必须是**已经在代码里接线**的功能
 *     （`ready: true`）或明确标「筹建中」（`ready: false`）。用户 2026-10-09 纠正过一次
 *     ——我自己臆造了三条消费点，那是替用户做产品决定。
 */

