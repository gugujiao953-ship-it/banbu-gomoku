/** 取某一级该发多少（超出表长时按最后一档 —— 宁可多发也不漏发）。 */
export const vcfLevelSoul = (level: number): number => {
  if (!Number.isFinite(level) || level < 1) return 0;
  const index = Math.min(Math.floor(level) - 1, VCF_LEVEL_SOUL.length - 1);
  return VCF_LEVEL_SOUL[index] ?? 0;
};

