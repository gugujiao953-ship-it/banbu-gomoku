import { chromium } from "playwright";
const file = process.argv[2];
if (!file) throw new Error("用法：node qa/export-roundtrip.mjs 松月.lib");
const base = process.env.QA_BASE_URL || "http://127.0.0.1:5173/";
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 412, height: 915 }, serviceWorkers: "block" });
const errors = [];
page.on("pageerror", (e) => errors.push(e.stack || String(e)));
await page.goto(base);
await page.locator('input[type="file"]').first().setInputFiles(file);
await page.waitForFunction(() => Boolean(window.__banbuImportDiagnostic) && !document.querySelector(".import-progress"), null, { timeout: 600000 });
const result = await page.evaluate(async () => {
  const branch = window.__banbuFindBranch?.();
  await new Promise(requestAnimationFrame);
  const before = { nodeCount: branch?.nodeCount || null, branchCount: branch?.branchCount || null };
  const buttonsBefore = [...document.querySelectorAll("button")].map((item) => item.textContent?.trim()).filter(Boolean);
  const notesTab = [...document.querySelectorAll("button")].find((item) => item.textContent?.trim().includes("记录"));
  notesTab?.click(); await new Promise(requestAnimationFrame);
  const exportButton = [...document.querySelectorAll("button")].find((item) => item.textContent?.trim().includes("导出"));
  if (!exportButton) return { before, exported: false, reason: "没有导出入口", buttonsBefore, buttonsAfter: [...document.querySelectorAll("button")].map((item) => item.textContent?.trim()).filter(Boolean) };
  exportButton.click(); await new Promise(requestAnimationFrame);
  const sgf = [...document.querySelectorAll("button")].find((item) => item.textContent?.includes("标准 SGF"));
  if (!sgf) return { before, exported: false, reason: "没有 SGF 导出按钮" };
  let downloaded = null;
  const listener = (event) => { downloaded = event; };
  sgf.addEventListener("click", listener, { once: true });
  sgf.click(); await new Promise((resolve) => setTimeout(resolve, 500));
  return { before, exported: true, sgfClick: Boolean(downloaded) };
});
console.log(JSON.stringify({ file, result, consoleErrors: errors }, null, 2));
await browser.close();
